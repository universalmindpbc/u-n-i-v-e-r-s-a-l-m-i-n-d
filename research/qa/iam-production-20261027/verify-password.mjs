import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {chromium} from '/Users/benkorbel/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
const origin='https://universalmind.tv';
const password=await fs.readFile('/private/tmp/iam-portal-requested-password.txt','utf8');
const expected=await fs.readFile(process.env.SOURCE_ROOT+'/index.html','utf8');
const response=await fetch(origin+'/',{cache:'no-store'});
assert.equal(response.status,200);
const actual=await response.text();
assert.equal(actual,expected,'Production portal source differs from the committed candidate');
assert.ok(!actual.includes(password),'Plaintext credential exposed');
const report={environment:'production',url:origin+'/',source_commit:process.env.SOURCE_COMMIT,portal_sha256:createHash('sha256').update(actual).digest('hex'),checks:[],errors:[]};
report.checks.push('HTTP 200 and byte-identical committed portal source');
console.log('Deployed portal source verified.');
const server=await chromium.launchServer({headless:true,timeout:20000,args:['--mute-audio','--autoplay-policy=user-gesture-required']});
assert.ok(server.process().spawnargs.includes('--mute-audio'));
console.log('Muted browser launched.');
const browser=await chromium.connect(server.wsEndpoint(),{timeout:20000});
console.log('Browser connected.');
try{
 const context=await browser.newContext({viewport:{width:1440,height:960}});
 context.setDefaultTimeout(15000);
 context.setDefaultNavigationTimeout(15000);
 const page=await context.newPage();
 console.log('Browser page ready.');
 page.on('pageerror',e=>report.errors.push(e.message));
 await page.goto(origin+'/',{waitUntil:'domcontentloaded'});
 console.log('Live portal loaded.');
 await page.locator('[data-access-password]').fill('invalid-portal-check-'+Date.now());
 await page.locator('[data-access-form]').evaluate(f=>f.requestSubmit());
 await page.waitForFunction(()=>document.querySelector('[data-access-error]').textContent==='password not recognised');
 assert.equal(page.url(),origin+'/');
 report.checks.push('Invalid password rejected on the live portal');
 console.log('Invalid password rejected.');
 const receipt=page.waitForResponse(r=>r.url()===origin+'/vogue/iam/api/portal-entry.php');
 await page.locator('[data-access-password]').fill(password);
 await page.locator('[data-access-form]').evaluate(f=>f.requestSubmit());
 const accepted=await receipt;
 console.log('Server response received:',accepted.status());
 assert.equal(accepted.status(),202);
 await page.waitForURL(origin+'/vogue/iam/induction.html',{timeout:15000});
 await page.waitForLoadState('domcontentloaded');
 assert.ok((await page.locator('body').innerText()).trim().length>0);
 const storage=await page.evaluate(()=>JSON.stringify({local:{...localStorage},session:{...sessionStorage}}));
 assert.ok(!storage.includes(password));
 report.checks.push('Requested password accepted; server entry response HTTP 202; induction page displayed');
 report.checks.push('Password absent from browser localStorage and sessionStorage');
 assert.deepEqual(report.errors,[]);
 report.checks.push('No browser page errors');
 await page.evaluate(()=>{document.querySelectorAll('audio,video').forEach(el=>el.pause());});
 await context.close();
}finally{await browser.close();await server.close();}
report.checks.push('Separate headless browser confirmed muted at process launch and closed after verification');
report.passed=true;
await fs.writeFile('/private/tmp/iam-production-audit-20261027/password-verification.json',JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
